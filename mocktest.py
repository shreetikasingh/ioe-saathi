# mocktest.py - generate a realistic IOE-style mock exam from 18 years of real questions
#
# How it works (no AI calls, instant and free):
#   * IOE papers have a fixed structure: Q2 is usually convolution, Q3 is the Z-transform...
#   * So for each question slot (Q1, Q2, ...) we pick one real past question that was asked
#     in that same slot.
#   * Questions that were repeated many times are more likely to be picked.
#   * The same repeated question never appears twice in one paper.

import random
import re
from collections import Counter

from patterns import load_questions, load_repeats

QUESTION_NUMBER = re.compile(r"^\s*(?:\*\*)?\d{1,2}\.(?:\*\*)?\s*")


def clean_text(text):
    """Remove the label line, the old question number and the end-of-paper stars."""
    body = text.split("\n", 1)[-1].replace("***", "").strip()
    return QUESTION_NUMBER.sub("", body, count=1)


def one_paper(by_slot, rng, times_asked, group_of):
    """Build one candidate paper: for each slot, pick a real question asked in that slot."""
    paper, used = [], set()
    for slot in sorted(by_slot):
        candidates = [
            row for row in by_slot[slot]
            if group_of.get(row["id"], row["id"]) not in used
        ]
        if not candidates:
            continue
        weights = [times_asked.get(row["id"], 1) for row in candidates]
        pick = rng.choices(candidates, weights=weights, k=1)[0]
        used.add(group_of.get(pick["id"], pick["id"]))
        paper.append({
            "text": clean_text(pick["text"]),
            "marks": int(pick["marks"]),
            "topic": pick["topic"],
            "from_exam": pick["exam"],
            "from_q": int(pick["question_no"]),
            "times_asked": times_asked.get(pick["id"], 1),
        })
    return paper


def build_mock_test(subject, seed, attempts=500):
    rng = random.Random(seed)  # same seed = same paper, so the page doesn't change on every click
    df = load_questions()
    # Only questions with a known exam and readable marks
    df = df[(df["subject"] == subject) & (df["exam"] != "Unknown exam") & (df["marks"] > 0)]

    # Which repeated-question group each past question belongs to, and how often it was asked
    times_asked, group_of = {}, {}
    for g, r in enumerate(load_repeats(subject)):
        for a in r["asked_in"]:
            times_asked[a["id"]] = r["times_asked"]
            group_of[a["id"]] = f"group-{g}"

    # IOE changed its paper format over the years (some papers have 10 questions, some 11).
    # Mixing formats breaks the marks total, so we copy the format of the RECENT papers
    # and only use questions from papers with that same format.
    per_exam = df.groupby("exam").agg(
        questions=("question_no", "max"), total=("marks", "sum"), year=("year", "max")
    )
    recent = per_exam.sort_values("year").tail(5)
    num_slots = Counter(recent["questions"]).most_common(1)[0][0]
    same_format = per_exam[per_exam["questions"] == num_slots]
    full_marks = Counter(same_format["total"]).most_common(1)[0][0]  # e.g. 80
    df = df[df["exam"].isin(same_format.index)]

    # All past questions grouped by their slot: {1: [questions asked as Q1], 2: [...], ...}
    by_slot = {
        slot: df[df["question_no"] == slot].to_dict("records")
        for slot in range(1, num_slots + 1)
    }

    # Mixing questions from different years can give 78 or 81 marks, so we build many
    # candidate papers and keep the first one whose total matches the real full marks
    best = None
    for _ in range(attempts):
        paper = one_paper(by_slot, rng, times_asked, group_of)
        gap = abs(sum(q["marks"] for q in paper) - full_marks)
        if best is None or gap < best[0]:
            best = (gap, paper)
        if gap == 0:
            break
    return best[1]


def due_topics(subject, recent_papers=4, min_share=0.4):
    """Topics that usually come in exams but were missing from the last few papers."""
    df = load_questions()
    df = df[(df["subject"] == subject) & (df["exam"] != "Unknown exam")]
    exams = df.drop_duplicates("exam").sort_values("year")["exam"].tolist()
    recent = set(exams[-recent_papers:])
    due = []
    for topic, group in df.groupby("topic"):
        share = group["exam"].nunique() / len(exams)
        if share >= min_share and not set(group["exam"]) & recent:
            last = group.sort_values("year")["exam"].iloc[-1]
            due.append((topic, share, last))
    return sorted(due, key=lambda d: -d[1])


def paper_as_markdown(subject, paper):
    total = sum(q["marks"] for q in paper)
    lines = [
        "# TRIBHUVAN UNIVERSITY · INSTITUTE OF ENGINEERING",
        f"## Mock Exam: {subject.upper()} (generated by IOE Saathi)",
        f"Full Marks: {total} · Time: 3 hrs",
        "",
        "*Attempt all questions. The figures in the margin indicate full marks.*",
        "",
    ]
    for i, q in enumerate(paper, start=1):
        lines.append(f"{i}. {q['text']}")
        lines.append("")
    return "\n".join(lines)


# ---------- The Streamlit page ----------
def render_mock_test(st, subject):
    st.markdown("### 📝 Smart Mock Test")
    st.caption(
        "A full practice paper built from real past questions. Each question slot follows "
        "IOE's real paper pattern (e.g. Q3 is usually the Z-transform), and questions that "
        "were repeated many times are more likely to appear."
    )

    if "mock_seed" not in st.session_state:
        st.session_state.mock_seed = random.randint(1, 1_000_000)
    if st.button("🎲 Generate a new mock test"):
        st.session_state.mock_seed = random.randint(1, 1_000_000)

    paper = build_mock_test(subject, st.session_state.mock_seed)
    if not paper:
        st.info("Not enough data yet to build a mock test for this subject.")
        return
    total = sum(q["marks"] for q in paper)

    # Exam paper header
    st.markdown(
        f"""
<div class="hero" style="padding:18px 24px; margin-top:8px;">
  <span class="tag">MOCK EXAM · {subject.upper()}</span>
  <p style="margin-top:4px;"><b>Full Marks: {total}</b> &nbsp;·&nbsp; Time: 3 hrs &nbsp;·&nbsp;
  {len(paper)} questions &nbsp;·&nbsp; Attempt all questions</p>
</div>
""",
        unsafe_allow_html=True,
    )

    for i, q in enumerate(paper, start=1):
        with st.container(border=True):
            hot = f'<span class="badge badge-hot">🔁 asked {q["times_asked"]}×</span>' if q["times_asked"] > 1 else ""
            st.markdown(
                f'<span class="badge badge-q">Q{i}</span>'
                f'<span class="badge badge-subj">{q["topic"]}</span>' + hot,
                unsafe_allow_html=True,
            )
            st.markdown(q["text"])
            st.caption(f"From {q['from_exam']}, Q{q['from_q']}")

    st.download_button(
        "⬇️ Download this paper",
        data=paper_as_markdown(subject, paper),
        file_name=f"ioe_saathi_mock_{subject}.md",
        mime="text/markdown",
    )

    due = due_topics(subject)
    if due:
        st.markdown("#### ⏰ Topics that might be 'due'")
        st.caption("They usually come in exams but were missing from the last 4 papers. Just a pattern, not a prediction!")
        for topic, share, last in due:
            st.markdown(f"- **{topic}**: came in {share:.0%} of papers, last asked in {last}")
